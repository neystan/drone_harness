REFLECTION_PROMPT = """反思：普通观察与四向搜索共用。收到新图时，对照当前子目标与原指令，按“动作预期→工具实际反馈→新观察变化→完成条件”核对参照物外观、邻近关系、路线顺序、动作执行及位置。
在同次看图回复开头输出一行JSON：{"target_status":"confirmed|uncertain|not_found","message":"关键判断依据或缺口"}，不加引导句或代码围栏；随后直接按需调用一个原生工具，不为判断单独结束回复或增加检查轮次。
confirmed仅确认参照物身份，不表示到位或完成；uncertain表示候选证据不足；not_found表示本次没找到，不代表不存在。测距有效或数值变小不能将存疑候选升级为confirmed。message只简述当前决定的关键依据或缺口，不反复罗列坐标、尺寸或多套假设；四图说明相对开始朝向的候选方向。
动作执行情况和实际位移以工具反馈为准，不把请求距离或下发距离直接当作实际位移；success=true也可能未移动，动作成功不代表方向合理或子目标完成。
是否真正接近、越过、穿过或到位，沿用空间与接近核验规则，对照实际移动、目标相对位置及边界变化；仅转向改变方位或目标消失不证明越过，接近不等于到达。
目标持续偏侧、移动后位置不符预期或关键线索缺失时，重新核对朝向和路线假设；身份确认后重点核对实际动作与位置条件。需新证据才调整视角并让observe.prompt聚焦一个疑点；证据充分直接继续，不提前找齐后续地标，不重复看相同图片求确认。
"""


def build_system_prompt(profile: RuntimeProfile) -> str:
    """生成基础行为规则，仅为实机补充逐动作审批要求。"""
    prompt = SYSTEM_PROMPT + REFLECTION_PROMPT + build_skills_index(profile.name)
    if profile.mode == "real":
        return prompt + (
            "实机六种飞行动作每次均须人工确认；调用前先 observe，等待批准后执行。"
            "超限请求会被拒绝，请按工具参数限额和深度上限规划。"
        )
    return prompt
